async def escalate_for_credentials(
    spec_dir: Path,
    project_dir: Path,
    detected_login_url: str | None = None
) -> Path:
    """
    Escalate to human for login credentials.

    Creates clear request explaining what's needed for E2E testing.
    """
    debug_section("qa_escalation", "Escalating for credentials")

    # Emit event for frontend
    emit_phase(ExecutionPhase.HUMAN_INPUT_NEEDED, "Login credentials required for E2E testing")

    additional_context = None
    if detected_login_url:
        additional_context = f"Detected login page at: `{detected_login_url}`"

    example_config = """{
  "credentials": {
    "default": {
      "username": "YOUR_TEST_USERNAME",
      "password": "YOUR_TEST_PASSWORD"
    }
  }
}"""

    escalation_file = create_escalation_file(
        spec_dir=spec_dir,
        escalation_type="NEED_CREDENTIALS",
        title="Login Credentials Required",
        description="""The E2E tests need to authenticate to test the application.
Without valid credentials, tests that require login will fail.

**Why this is needed:**
- Playwright needs to fill in login form
- Tests behind authentication cannot proceed
- This is a one-time setup - credentials will be reused for all future QA iterations""",
        required_inputs=[
            {
                "name": "Username / Email",
                "description": "The test account username or email address",
                "example": "test@example.com"
            },
            {
                "name": "Password",
                "description": "The test account password",
                "example": "testpassword123"
            }
        ],
        example_config=example_config,
        additional_context=additional_context
    )

    # Print to console for visibility
    print("\n" + "=" * 70)
    print("  HUMAN INPUT NEEDED: Login Credentials")
    print("=" * 70)
    print("\nQA E2E tests require login credentials to proceed.")
    print(f"\nSee: {escalation_file}")
    print("\nProvide credentials in qa_config.json and re-run --qa")
    print("=" * 70 + "\n")

    return escalation_file


async def escalate_for_dev_server(
    spec_dir: Path,
    project_dir: Path
) -> Path:
    """
    Escalate to human for dev server configuration.

    Includes auto-detected suggestions if available.
    """
    debug_section("qa_escalation", "Escalating for dev server config")

    # Emit event for frontend
    emit_phase(ExecutionPhase.HUMAN_INPUT_NEEDED, "Dev server configuration required")

    # Try to provide helpful suggestions
    guessed_config = guess_dev_server_config(project_dir)

    additional_context = None
    if guessed_config:
        additional_context = f"""**Auto-detected suggestion:**
- Start command: `{guessed_config.get('start_command', 'unknown')}`
- Base URL: `{guessed_config.get('base_url', 'unknown')}`

Please verify these are correct for your project."""

    example_config = """{
  "dev_server": {
    "start_command": "npm run dev",
    "base_url": "http://localhost:3000",
    "health_check_url": "http://localhost:3000/api/health",
    "startup_timeout_seconds": 30
  }
}"""

    escalation_file = create_escalation_file(
        spec_dir=spec_dir,
        escalation_type="NEED_DEV_SERVER",
        title="Dev Server Configuration Required",
        description="""The E2E tests need to know how to start and access the development server.
Without this, Playwright cannot navigate to your application.

**Why this is needed:**
- QA needs to start the dev server before running E2E tests
- Playwright needs the base URL to navigate to pages
- Health check ensures server is ready before tests begin""",
        required_inputs=[
            {
                "name": "Start Command",
                "description": "Command to start the development server",
                "example": "npm run dev"
            },
            {
                "name": "Base URL",
                "description": "URL where the dev server will be accessible",
                "example": "http://localhost:3000"
            },
            {
                "name": "Health Check URL (optional)",
                "description": "URL to check if server is ready (defaults to base URL)",
                "example": "http://localhost:3000/api/health"
            }
        ],
        example_config=example_config,
        additional_context=additional_context
    )

    # Print to console for visibility
    print("\n" + "=" * 70)
    print("  HUMAN INPUT NEEDED: Dev Server Configuration")
    print("=" * 70)
    print("\nQA E2E tests need to know how to start your dev server.")

    if guessed_config:
        print(f"\nAuto-detected suggestion:")
        print(f"  Start: {guessed_config.get('start_command', '?')}")
        print(f"  URL:   {guessed_config.get('base_url', '?')}")
        print("\nPlease verify and add to qa_config.json")
    else:
        print("\nCould not auto-detect - please configure manually.")

    print(f"\nSee: {escalation_file}")
    print("=" * 70 + "\n")

    return escalation_file


async def escalate_recurring_issues(
    spec_dir: Path,
    recurring_issues: list[dict],
    iteration_count: int
) -> Path:
    """
    Escalate to human when same issues keep recurring.

    This indicates the automated fixes aren't working and human
    judgment is needed.
    """
    debug_section("qa_escalation", "Escalating recurring issues")

    emit_phase(ExecutionPhase.HUMAN_INPUT_NEEDED,
               f"{len(recurring_issues)} recurring issues need human review")

    # Format issue list
    issues_text = ""
    for i, issue in enumerate(recurring_issues, 1):
        issues_text += f"""
### Issue {i}: {issue.get('title', 'Unknown')}

**Occurrences:** {issue.get('recurrence_count', '?')} times
**First seen:** Iteration {issue.get('found_in', '?')}
**Location:** `{issue.get('location', 'Unknown')}`

**Previous fix attempts:**
"""
        for attempt in issue.get('fix_attempts', []):
            issues_text += f"- {attempt.get('iteration', '?')}: {attempt.get('fix_description', 'Unknown')} → {attempt.get('outcome', 'Unknown')}\n"
            if attempt.get('reason'):
                issues_text += f"  Reason: {attempt.get('reason')}\n"

    content = f"""# QA Needs Human Review

**Type:** RECURRING_ISSUES
**Created:** {datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")}
**Spec:** {spec_dir.name}
**Iterations completed:** {iteration_count}

---

## Recurring Issues Detected

The following issues have appeared **3 or more times** despite fix attempts.
Automated fixes are not resolving them - human judgment is needed.

{issues_text}

---

## What You Can Do

1. **Review the issues above** - understand what's failing and why fixes aren't working

2. **Option A: Fix manually**
   - Make the fix yourself in the codebase
   - Run `python run.py --spec {spec_dir.name.split('-')[0]} --qa` to re-validate

3. **Option B: Mark as acceptable**
   - If this is expected behavior, add to `qa_config.json`:
   ```json
   {{
     "human_approvals": {{
       "known_acceptable_issues": ["{recurring_issues[0].get('title', 'issue_name')}"]
     }}
   }}
   ```

4. **Option C: Skip specific tests**
   - If tests are flaky, add to `qa_config.json`:
   ```json
   {{
     "human_approvals": {{
       "skip_flaky_tests": ["test_name_here"]
     }}
   }}
   ```

---

## Files for Context

- `qa_report.md` - Latest QA report with full details
- `QA_FIX_REQUEST.md` - Last fix request sent to fixer
- `implementation_plan.json` - Full iteration history

---

_QA loop has been paused. Will resume when you re-run --qa._
"""

    escalation_file = spec_dir / "QA_HUMAN_REVIEW_NEEDED.md"
    escalation_file.write_text(content)

    print("\n" + "=" * 70)
    print("  RECURRING ISSUES - Human Review Needed")
    print("=" * 70)
    print(f"\n{len(recurring_issues)} issue(s) have appeared 3+ times despite fixes.")
    print("\nAutomated QA cannot resolve these. Please review:")
    for issue in recurring_issues[:3]:
        print(f"  - {issue.get('title', 'Unknown')}")
    print(f"\nSee: {escalation_file}")
    print("=" * 70 + "\n")

    return escalation_file


