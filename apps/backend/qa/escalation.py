def has_pending_escalation(spec_dir: Path) -> tuple[bool, str | None]:
    """
    Check if there's a pending escalation that needs human input.

    Returns:
        (has_pending, escalation_type) tuple
    """
    # Check for escalation files
    escalation_files = [
        ("QA_HUMAN_INPUT_NEEDED.md", "input_needed"),
        ("QA_HUMAN_REVIEW_NEEDED.md", "review_needed"),
    ]

    for filename, esc_type in escalation_files:
        if (spec_dir / filename).exists():
            debug("qa_escalation", f"Found pending escalation: {filename}")
            return True, esc_type

    return False, None


def clear_escalation(spec_dir: Path) -> bool:
    """
    Clear escalation files after human has provided input.

    Called when QA prerequisites are now met.
    """
    escalation_files = [
        "QA_HUMAN_INPUT_NEEDED.md",
        "QA_HUMAN_REVIEW_NEEDED.md",
    ]

    cleared = False
    for filename in escalation_files:
        filepath = spec_dir / filename
        if filepath.exists():
            filepath.unlink()
            debug_success("qa_escalation", f"Cleared escalation: {filename}")
            cleared = True

    return cleared


