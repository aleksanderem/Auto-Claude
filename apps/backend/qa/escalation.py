def create_escalation_file(
    spec_dir: Path,
    escalation_type: str,
    title: str,
    description: str,
    required_inputs: list[dict],
    example_config: str,
    additional_context: str | None = None
) -> Path:
    """
    Create a human-readable escalation request file.

    Args:
        spec_dir: Spec directory
        escalation_type: Type of escalation (for tracking)
        title: Human-readable title
        description: What's needed and why
        required_inputs: List of {name, description, example} dicts
        example_config: Example qa_config.json snippet
        additional_context: Optional extra information

    Returns:
        Path to created escalation file
    """
    escalation_file = spec_dir / "QA_HUMAN_INPUT_NEEDED.md"

    timestamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")

    content = f"""# QA Needs Human Input

**Type:** {escalation_type}
**Created:** {timestamp}
**Spec:** {spec_dir.name}

---

## {title}

{description}

---

## Required Information

"""

    for inp in required_inputs:
        content += f"### {inp['name']}\n"
        content += f"{inp['description']}\n"
        if inp.get('example'):
            content += f"\n**Example:** `{inp['example']}`\n"
        content += "\n"

    content += f"""---

## How to Provide

Edit `{spec_dir.name}/qa_config.json`:

```json
{example_config}
```

**Then re-run QA:**
```bash
python run.py --spec {spec_dir.name.split('-')[0]} --qa
```

"""

    if additional_context:
        content += f"""---

## Additional Context

{additional_context}

"""

    content += f"""---

_This file was auto-generated by Ouro QA._
_It will be removed once you provide the required input and re-run QA._
"""

    escalation_file.write_text(content)

    debug_success("qa_escalation", f"Created escalation file: {escalation_file}")

    return escalation_file


