async def apply_auto_detected_config(spec_dir: Path, project_dir: Path) -> bool:
    """
    Apply auto-detected configuration (dev server) if user hasn't configured.

    This provides sensible defaults that can be overridden.
    Returns True if any config was auto-applied.
    """
    config = load_qa_config(spec_dir) or create_default_qa_config(spec_dir, spec_dir.name)
    applied = False

    # Auto-apply dev server config if not set
    if not config.get("dev_server") or not config["dev_server"].get("start_command"):
        guessed = guess_dev_server_config(project_dir)
        if guessed:
            config["dev_server"] = DevServerConfig(
                start_command=guessed.get("start_command", ""),
                base_url=guessed.get("base_url", ""),
                health_check_url=guessed.get("base_url", ""),
                startup_timeout_seconds=30,
                provided_by_human=False,  # Mark as auto-detected
                provided_at=datetime.now(timezone.utc).isoformat(),
            )
            applied = True
            debug("qa_escalation", "Auto-applied dev server config",
                  command=guessed.get("start_command"),
                  url=guessed.get("base_url"))

    if applied:
        save_qa_config(spec_dir, config)

    return applied
