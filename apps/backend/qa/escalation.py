"""
QA Escalation to Human
=======================

Handles escalation of QA blockers to human intervention.
Creates clear, actionable requests and pauses QA until resolved.

Escalation types:
- NEED_CREDENTIALS: Login credentials required for E2E testing
- NEED_DEV_SERVER: Dev server configuration required
- RECURRING_ISSUE: Same issue appearing 3+ times
- MAX_ITERATIONS: Reached maximum QA iterations
- CUSTOM_BLOCKER: Project-specific blocker needing human decision
"""

